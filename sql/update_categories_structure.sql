-- 1. 기존 테이블 구조 확인
SHOW CREATE TABLE categories;
DESCRIBE categories;

-- 2. 기존 데이터 확인
SELECT id, name, name_en, icon_class FROM categories ORDER BY id;

-- 3. 테이블 구조는 수정하지 않음 (이미 완벽함)
-- name 컬럼 = 한글명 저장용
-- name_en 컬럼 = 영문명 저장용

-- ================================================
